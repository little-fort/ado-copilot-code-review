<#
    Tests for the agent-thread filter in Get-AzureDevOpsPR.ps1 (PR #61 review).

    Test-AgentAuthoredThread decides which existing comment threads belong to a
    previous automated review and therefore enter the COPILOT COMMENT THREADS
    JSON that the agent may resolve. A false positive here leaks human threads
    to the agent — the original -like implementation did exactly that, because
    [brackets] in a wildcard pattern form a character class rather than literal
    text. The function is extracted via the PowerShell AST for direct unit
    testing.

    Requires Pester 5+. Run via: pwsh -File tests/powershell/Invoke-Tests.ps1
#>

BeforeAll {
    $repoRoot = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
    $script:PrScript = Join-Path $repoRoot 'CopilotCodeReviewV1/scripts/Get-AzureDevOpsPR.ps1'

    $tokens = $null
    $parseErrors = $null
    $ast = [System.Management.Automation.Language.Parser]::ParseFile($PrScript, [ref]$tokens, [ref]$parseErrors)
    if ($parseErrors.Count -gt 0) {
        throw "Get-AzureDevOpsPR.ps1 failed to parse: $($parseErrors -join '; ')"
    }
    # Test-AgentAuthoredThread delegates to Test-AgentAuthoredComment (PR #65
    # rework), so both are loaded
    foreach ($functionName in 'Test-AgentAuthoredComment', 'Test-AgentAuthoredThread') {
        $funcAst = $ast.Find({
            param($node)
            $node -is [System.Management.Automation.Language.FunctionDefinitionAst] -and
            $node.Name -eq $functionName
        }, $true)
        if (-not $funcAst) {
            throw "$functionName function not found in Get-AzureDevOpsPR.ps1 — update this test if it was renamed."
        }
        . ([scriptblock]::Create($funcAst.Extent.Text))
    }

    $previewAst = $ast.Find({
        param($node)
        $node -is [System.Management.Automation.Language.FunctionDefinitionAst] -and
        $node.Name -eq 'Get-CommentPreviewLines'
    }, $true)
    if (-not $previewAst) {
        throw 'Get-CommentPreviewLines function not found in Get-AzureDevOpsPR.ps1 — update this test if it was renamed.'
    }
    . ([scriptblock]::Create($previewAst.Extent.Text))

    # Builds a minimal thread object shaped like the ADO threads API response
    function New-Thread {
        param(
            [string]$Content,
            [string]$DisplayName = 'Jane Reviewer',
            [string]$UniqueName = 'jane@example.com'
        )
        [pscustomobject]@{
            comments = @(
                [pscustomobject]@{
                    content = $Content
                    author  = [pscustomobject]@{
                        displayName = $DisplayName
                        uniqueName  = $UniqueName
                    }
                }
            )
        }
    }
}

Describe 'Test-AgentAuthoredThread' {

    It 'rejects an ordinary human comment' {
        # Regression for the -like character-class bug: this text contains many
        # letters from the attribution tag but not the tag itself
        Test-AgentAuthoredThread -Thread (New-Thread -Content 'Please fix the null check here.') | Should -BeFalse
    }

    It 'rejects a human comment that mentions the agent without the bracketed tag' {
        Test-AgentAuthoredThread -Thread (New-Thread -Content 'This was Generated by GitHub Copilot, I think?') | Should -BeFalse
    }

    It 'accepts a thread authored by the Build Service identity' {
        $thread = New-Thread -Content 'Anything at all' -DisplayName 'TestProject Build Service (testorg)' -UniqueName 'build@testorg'
        Test-AgentAuthoredThread -Thread $thread | Should -BeTrue
    }

    It 'accepts a Build Service match on uniqueName alone' {
        $thread = New-Thread -Content 'Anything at all' -DisplayName 'Service Account' -UniqueName 'svc.Build Service.testorg'
        Test-AgentAuthoredThread -Thread $thread | Should -BeTrue
    }

    It 'accepts a PAT-authored comment carrying the Copilot attribution tag' {
        Test-AgentAuthoredThread -Thread (New-Thread -Content "Looks good!`n`n[Generated by GitHub Copilot]") | Should -BeTrue
    }

    It 'accepts a PAT-authored comment carrying the Claude Code attribution tag' {
        Test-AgentAuthoredThread -Thread (New-Thread -Content "Consider renaming this.`n`n[Generated by Claude Code]") | Should -BeTrue
    }
}

Describe 'Get-CommentPreviewLines' {

    It 'counts only non-blank lines as omitted' {
        # Blank lines are never displayed, so they must not inflate the
        # "(N more lines)" note (the old code reported Count - 3 regardless)
        $preview = Get-CommentPreviewLines -Content "one`n`n two `r`nthree`n`nfour" -MaxLines 2
        $preview.Lines | Should -Be @('one', 'two')
        $preview.Omitted | Should -Be 2
    }

    It 'reports nothing omitted when the comment fits' {
        $preview = Get-CommentPreviewLines -Content "a`nb`nc`nd" -MaxLines 30
        $preview.Lines.Count | Should -Be 4
        $preview.Omitted | Should -Be 0
    }

    It 'handles empty content' {
        $preview = Get-CommentPreviewLines -Content $null -MaxLines 5
        $preview.Lines.Count | Should -Be 0
        $preview.Omitted | Should -Be 0
    }
}

Describe 'Get-AzureDevOpsPR.ps1 thread context (issue #67)' {

    BeforeAll {
        . (Join-Path $PSScriptRoot 'MockApiHelper.ps1')

        $script:PrJson = @{
            pullRequestId = 9
            title         = 'Thread context test'
            description   = 'Test PR'
            status        = 'active'
            repository    = @{ name = 'TestRepo' }
            sourceRefName = 'refs/heads/feature'
            targetRefName = 'refs/heads/main'
            isDraft       = $false
            mergeStatus   = 'succeeded'
            createdBy     = @{ displayName = 'Dev'; uniqueName = 'dev@example.com' }
            creationDate  = '2026-01-01T00:00:00Z'
            reviewers     = @()
        } | ConvertTo-Json -Depth 5

        function New-Comment {
            param([int]$Id, [string]$Content, [string]$Author = 'Jane Reviewer', [switch]$Deleted)
            $comment = @{
                id            = $Id
                commentType   = 'text'
                content       = $Content
                author        = @{ displayName = $Author; uniqueName = "$($Author -replace ' ', '.')@example.com" }
                publishedDate = '2026-01-02T00:00:00Z'
            }
            if ($Deleted) {
                $comment.isDeleted = $true
                $comment.Remove('content')
            }
            $comment
        }

        function Get-NumberedLines {
            param([string]$Prefix, [int]$Count)
            (1..$Count | ForEach-Object { "$Prefix line $_" }) -join "`n"
        }

        # 21: automated review (Build Service), with one real and one deleted reply
        # 22: resolved human thread, 12 lines
        # 23: active human inline thread, 40 lines, with a disputing reply
        # 24: active human thread, 4 lines
        $script:ThreadsJson = @{
            count = 4
            value = @(
                @{
                    id       = 21
                    status   = 'active'
                    comments = @(
                        (New-Comment -Id 1 -Content "Agent finding A`nAgent finding B" -Author 'TestProject Build Service (testorg)'),
                        (New-Comment -Id 2 -Content 'Fixed in the latest push.' -Author 'Dev'),
                        (New-Comment -Id 3 -Deleted -Author 'Dev')
                    )
                },
                @{
                    id       = 22
                    status   = 'fixed'
                    comments = @((New-Comment -Id 1 -Content (Get-NumberedLines 'Resolved' 12)))
                },
                @{
                    id            = 23
                    status        = 'active'
                    threadContext = @{ filePath = '/src/app.cs'; rightFileStart = @{ line = 42; offset = 1 } }
                    comments      = @(
                        (New-Comment -Id 1 -Content (Get-NumberedLines 'Open' 40)),
                        (New-Comment -Id 2 -Content 'I disagree; keeping this as is.' -Author 'Dev')
                    )
                },
                @{
                    id       = 24
                    status   = 'active'
                    comments = @((New-Comment -Id 1 -Content (Get-NumberedLines 'Short' 4)))
                }
            )
        } | ConvertTo-Json -Depth 8

        # Runs the script against the fixture; returns the PR_Details.txt text
        function Invoke-PrDetails {
            param([switch]$IncludeHumanThreads)

            $outDir = Join-Path $TestDrive ([guid]::NewGuid().ToString('N'))
            New-Item -ItemType Directory -Path $outDir | Out-Null
            $outFile = Join-Path $outDir 'PR_Details.txt'
            $prScript = $PrScript
            $extraArgs = if ($IncludeHumanThreads) { @('-IncludeHumanThreads') } else { @() }

            $result = Invoke-ScriptWithMockApi -Responses @(
                @{ Status = 200; Body = $PrJson },
                @{ Status = 200; Body = '{"count":0,"value":[]}' },
                @{ Status = 200; Body = '{"count":1,"value":[{"id":1,"updatedDate":"2026-01-01T00:00:00Z"}]}' },
                @{ Status = 200; Body = $ThreadsJson }
            ) -BuildArgs {
                param($baseUrl)
                @('-File', $prScript,
                  '-Token', 'test-token', '-CollectionUri', "$baseUrl/testorg",
                  '-Project', 'TestProject', '-Repository', 'TestRepo',
                  '-Id', '9', '-OutputFile', $outFile) + $extraArgs
            }.GetNewClosure()

            $result.ExitCode | Should -Be 0
            Get-Content -Path $outFile -Raw
        }

        # Returns the raw JSON line printed between a section's start and end markers
        function Get-JsonSection {
            param([string]$Text, [string]$Name)
            $match = [regex]::Match($Text, "=== $([regex]::Escape($Name)) \(JSON\) ===\r?\n(.*?)\r?\n=== END ")
            if ($match.Success) { $match.Groups[1].Value } else { $null }
        }

        # Returns the prose summary block for one thread
        function Get-ThreadBlock {
            param([string]$Text, [int]$Id)
            [regex]::Match($Text, "(?s)  Thread #$Id \[.*?(?=\r?\n\r?\n|\r?\n  Thread #|\r?\n\[Linked Work Items\])").Value
        }
    }

    Context 'without -IncludeHumanThreads' {

        BeforeAll {
            $script:Text = Invoke-PrDetails
        }

        It 'prints an automated-review thread once, in the JSON section, with a pointer in the summary' {
            $block = Get-ThreadBlock $Text 21
            $block | Should -Match 'full text in the COPILOT COMMENT THREADS \(JSON\) section'
            $block | Should -Not -Match 'Agent finding A'
            ([regex]::Matches($Text, 'Agent finding A')).Count | Should -Be 1
        }

        It 'serializes a single automated-review thread as a JSON array' {
            $json = Get-JsonSection $Text 'COPILOT COMMENT THREADS'
            $json | Should -Match '^\['
            $threads = ConvertFrom-Json -InputObject $json -NoEnumerate
            @($threads).Count | Should -Be 1
            $threads[0].threadId | Should -Be 21
            # Soft-deleted replies carry no content and are left out
            @($threads[0].replies).Count | Should -Be 1
        }

        It 'shows a 5-line preview of a resolved thread with an accurate omitted count' {
            $block = Get-ThreadBlock $Text 22
            $block | Should -Match 'Resolved line 5'
            $block | Should -Not -Match 'Resolved line 6'
            $block | Should -Match '\(7 more lines\)'
        }

        It 'shows up to 30 lines of an open thread' {
            $block = Get-ThreadBlock $Text 23
            $block | Should -Match 'Open line 30'
            $block | Should -Not -Match 'Open line 31'
            $block | Should -Match '\(10 more lines\)'
        }

        It 'adds no omitted-lines note when the whole comment is shown' {
            $block = Get-ThreadBlock $Text 24
            $block | Should -Match 'Short line 4'
            $block | Should -Not -Match 'more lines'
        }

        It 'emits no human reviewer section' {
            $Text | Should -Not -Match 'HUMAN REVIEWER THREADS'
        }
    }

    Context 'with -IncludeHumanThreads' {

        BeforeAll {
            $script:Text = Invoke-PrDetails -IncludeHumanThreads
            $script:HumanThreads = ConvertFrom-Json -InputObject (Get-JsonSection $Text 'HUMAN REVIEWER THREADS')
        }

        It 'lists only active human threads' {
            @($HumanThreads | ForEach-Object { $_.threadId }) | Should -Be @(23, 24)
        }

        It 'includes the author, ids, file position, full text, and replies' {
            $thread = $HumanThreads | Where-Object { $_.threadId -eq 23 }
            $thread.commentId | Should -Be 1
            $thread.author | Should -Be 'Jane Reviewer'
            $thread.filePath | Should -Be '/src/app.cs'
            $thread.startLine | Should -Be 42
            $thread.content | Should -Match 'Open line 40'
            $thread.replies[0].author | Should -Be 'Dev'
            $thread.replies[0].content | Should -Be 'I disagree; keeping this as is.'
        }

        It 'points to the JSON section instead of repeating the text in the summary' {
            $block = Get-ThreadBlock $Text 23
            $block | Should -Match 'HUMAN REVIEWER THREADS \(JSON\) section'
            $block | Should -Not -Match 'Open line 1\b'
        }

        It 'keeps the preview for resolved human threads' {
            Get-ThreadBlock $Text 22 | Should -Match '\(7 more lines\)'
        }
    }
}
